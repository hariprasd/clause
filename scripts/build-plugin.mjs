//   Silent by default: the UI iframe is hidden, updates are pushed by the server over SSE, errors surface as a Figma toast.
//   Clause Assist — pieces live in scripts/plugin/ (annotate-glue.js, ui.html). Menu: Start (silent) · Open Clause Assist. "Start (silent)" · "Show panel" (same plugin, visible status panel + HTML drop zone).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { PROTOCOL_VERSION } from "@clause/contract/version";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// --out <dir> builds somewhere else (used by scripts/check-artifacts.mjs to prove the committed
// plugin matches its source without touching it).
const outIndex = process.argv.indexOf("--out");
const dir = outIndex > 0 ? resolve(process.argv[outIndex + 1]) : resolve(root, "figma-plugin");
mkdirSync(dir, { recursive: true });

// The build stamp is deterministic: a hash of the plugin's own sources, so it changes when the
// plugin changes and never because of a clock. A wall-clock stamp made every build dirty the tree
// and made "are the committed artifacts in sync" impossible to check.
const stamp = process.env.CLAUSE_STAMP || (() => {
  const inputs = [
    "scripts/runtime.js",
    "scripts/extract.js",
    "scripts/plugin/annotate-glue.js",
    "scripts/plugin/extract-ds.js",
    "scripts/plugin/ui.html",
  ];
  const hash = createHash("sha256");
  for (const f of inputs) hash.update(readFileSync(resolve(root, f)));
  const { version } = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
  return `${version}+${hash.digest("hex").slice(0, 7)}`;
})();
const runtime = readFileSync(resolve(root, "scripts/runtime.js"), "utf8");
const extract = readFileSync(resolve(root, "scripts/extract.js"), "utf8");
const annGlue = readFileSync(resolve(root, "scripts/plugin/annotate-glue.js"), "utf8");
const dsExtractSrc = readFileSync(resolve(root, "scripts/plugin/extract-ds.js"), "utf8");
const PORT = process.env.PORT || 8787;
const ui = readFileSync(resolve(root, "scripts/plugin/ui.html"), "utf8")
  .replace(/__PORT__/g, String(PORT))
  .replace(/__BUILD__/g, stamp)
  .replace(/__PROTOCOL__/g, String(PROTOCOL_VERSION));

writeFileSync(resolve(dir, "manifest.json"), JSON.stringify({
  name: "Clause Assist",
  id: "clause-assist-dev",
  api: "1.0.0",
  main: "code.js",
  ui: "ui.html",
  editorType: ["figma"],
  documentAccess: "dynamic-page",
  permissions: ["teamlibrary"],
  enablePrivatePluginApi: true, // exposes figma.fileKey (used for comments and links)
  menu: [{ name: "Open Clause Assist", command: "panel" }, { name: "Start (silent)", command: "start" }, { name: "Extract components & tokens", command: "extract" }],
  networkAccess: { allowedDomains: ["none"], devAllowedDomains: [`http://localhost:${PORT}`] },
}, null, 2));

